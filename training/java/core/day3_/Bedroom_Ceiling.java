package com.day3_;

public class Bedroom_Ceiling {
    private int height;
    private int paintedColor;

    public Bedroom_Ceiling(int height, int paintedColor) {
        this.height = height;
        this.paintedColor = paintedColor;
    }

    public int getHeight() {
        return height;
    }

    public int getPaintedColor() {
        return paintedColor;
    }
}