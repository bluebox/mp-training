//Type Casting
public class Example2 {
	public static void main(String args[])
	{
		int a = 10;
		float f = a;
		System.out.println("Value of a is"+ f);
		
		float floatValue = 10f;
		int ans = (int)floatValue;
		System.out.println("Value of ans is"+ ans);
		
		int value = 10;
		double ans1 = value;
		System.out.println("value of ans1 is"+ans1);
		
		double Value1 = 100.000d;
		int ans2=(int) Value1;
		System.out.println("value of ans2 is "+ ans2);
		
		
		
	}

}
