from abc import ABC, abstractmethod
from datetime import datetime

class SmartDevice(ABC):
    _device_counter = 0

    def __init__(self, device_id):
        self._device_id = device_id
        self.__is_on = False
        SmartDevice._device_counter += 1

    def turn_on(self):
        self.__is_on = True
        print(f"Device {self._device_id} turned on.")

    def turn_off(self):
        self.__is_on = False
        print(f"Device {self._device_id} turned off.")

    @property
    def is_on(self):
        return self.__is_on

    @abstractmethod
    def get_status_report(self):
        pass

    @abstractmethod
    def perform_action(self, action_type, value=None):
        pass

    @classmethod
    def get_device_count(cls):
        return cls._device_counter

    @staticmethod
    def get_system_time():
        return datetime.now().strftime("%Y-%m-%d %H:%M:%S")

class SmartLight(SmartDevice):
    def __init__(self, device_id):
        super().__init__(device_id)
        self.__brightness = 0

    @property
    def brightness(self):
        return self.__brightness

    @brightness.setter
    def brightness(self, value):
        if not self.is_on:
            print("Light is not turned on")
            return
        if 0 <= value <= 100:
            self.__brightness = value
            print(f"Brightness set to {value}%.")
        else:
            print("brightness should be between 0 and 100")

    def get_status_report(self):
        return f"SmartLight {self._device_id} - On: {self.is_on}, Brightness: {self.__brightness}%"

    def perform_action(self, action_type, value=None):
        if action_type == "set_brightness":
            self.brightness = value
        else:
            print("Action invalid")

class SmartThermostat(SmartDevice):
    def __init__(self, device_id):
        super().__init__(device_id)
        self.__temperature = 20.0

    @property
    def temperature(self):
        return self.__temperature

    @temperature.setter
    def temperature(self, value):
        if not self.is_on:
            print("Thermostat is not turned on")
            return
        if 18.0 <= value <= 30.0:
            self.__temperature = value
            print(f"Temperature set to {value}C.")
        else:
            print("Oops Temperature should be between 18 and 30")

    def get_status_report(self):
        return f"SmartThermostat {self._device_id} - On: {self.is_on}, Temperature: {self.__temperature}C"

    def perform_action(self, action_type, value=None):
        if action_type == "set_temperature":
            self.temperature = value
        else:
            print("Invalid action")

